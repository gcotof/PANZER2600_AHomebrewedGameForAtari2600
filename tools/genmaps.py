BANDS, W = 22, 16
def full(art):
    top = [r for r in art.strip().split("\n")]
    assert len(top) == 11 and all(len(r) == 16 for r in top), art
    return top + top[::-1]                   # 22 filas: la fila 10 se repite como 11
def solid(rows, col):                       # col 0..39 de pantalla
    c = col if col < 20 else 39 - col
    if c < 4: return False
    return rows[c - 4] == '#'
def tank_hits(g, tx, ty):
    for b in range((ty - 4) >> 2, ((ty + 3) >> 2) + 1):
        if not (0 <= b < BANDS): continue
        for col in range((tx - 15) >> 2, ((tx - 8) >> 2) + 1):
            if solid_cell(g, b, col): return True
    return False
def solid_cell(g, b, col):
    c = col if col < 20 else 39 - col
    return c >= 4 and g[b][c - 4] == '#'
def bfs(g):
    s, e = (56, 44), (126, 44)
    assert not tank_hits(g, *s) and not tank_hits(g, *e), "spawn bloqueado"
    seen, q = {s}, [s]
    while q:
        x, y = q.pop()
        for dx, dy in ((1,0),(-1,0),(0,1),(0,-1)):
            n = (x+dx, y+dy)
            if n in seen or not (19 <= n[0] < 164 and 5 <= n[1] < 86): continue
            if tank_hits(g, *n): continue
            seen.add(n); q.append(n)
    return e in seen, len(seen)
